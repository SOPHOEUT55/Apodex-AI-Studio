export function getLanguage(code?: string): LanguageInfo {
  const target = code || 'en';
  return (
    SUPPORTED_LANGUAGES.find((l) => l.code === target) ||
    SUPPORTED_LANGUAGES.find((l) => l.code === target.split('-')[0]) ||
    SUPPORTED_LANGUAGES[0]
  );
}

export function t(key: string, lang = 'en'): string {
  const langDict = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS['en'];
  if (langDict && langDict[key]) return langDict[key];
  return UI_TRANSLATIONS['en'][key] || key;
}

export function getPresetScripts(lang = 'en'): PresetScript[] {
  if (PRESET_SCRIPTS_BY_LANG[lang]) {
    return PRESET_SCRIPTS_BY_LANG[lang];
  }
  const prefix = lang.split('-')[0];
  if (PRESET_SCRIPTS_BY_LANG[prefix]) {
    return PRESET_SCRIPTS_BY_LANG[prefix];
  }
  return PRESET_SCRIPTS_BY_LANG['en'];
}

export function getTtsCode(lang = 'en'): string {
  const langInfo = getLanguage(lang);
  return langInfo.ttsLang || 'en-US';
}
